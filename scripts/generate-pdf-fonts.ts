/**
 * Regenerates `src/components/chat/pdf-fonts.ts` from the TTF faces vendored in
 * `src/assets/fonts/`. `next/font` self-hosts the site typeface as .woff2, which
 * jsPDF cannot read, so the PDF export carries its own base64 copy.
 *
 *   npm run pdf:fonts
 *
 * Re-running without changing a face rewrites byte-identical output, so the
 * committed module and the vendored faces can never silently drift.
 *
 * The faces themselves are produced once, outside the build, with fontTools
 * (`python3 -m pip install --user fonttools brotli`). Each static weight is
 * instanced out of the upstream variable font first — embedding the variable
 * font directly would make jsPDF render both styles at the default weight, so
 * bold would look identical to regular:
 *
 *   python3 -m fontTools.varLib.instancer --update-name-table \
 *     'HankenGrotesk[wght].ttf' wght=700 -o instance.ttf
 *   python3 -m fontTools.varLib.instancer --update-name-table \
 *     'NotoSans[wdth,wght].ttf' wdth=100 wght=700 -o instance.ttf
 *
 *   pyftsubset instance.ttf --output-file=<face>.ttf --unicodes=<ranges> \
 *     --layout-features= --drop-tables+=GSUB,GPOS,GDEF,STAT,gasp,prep \
 *     --no-hinting --desubroutinize --notdef-outline \
 *     --name-IDs=0,1,2,3,4,5,6,13,14
 *
 * Ranges: Hanken Grotesk keeps Latin and Latin-Extended; Noto Sans keeps
 * Cyrillic plus the Latin needed for German clinic names, URLs and addresses,
 * which appear in a Russian or Ukrainian sheet too. Hanken Grotesk has no basic
 * Cyrillic block at all, which is why the second family exists.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { basename } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const FONT_ROOT = new URL('../src/assets/fonts/', import.meta.url);
const OUTPUT = new URL('../src/components/chat/pdf-fonts.ts', import.meta.url);

export type FontStyle = 'normal' | 'bold';
export type FaceSource = { family: string; style: FontStyle; source: string };
export type EmbeddedFace = FaceSource & { file: string; data: string };

const FACES: readonly FaceSource[] = [
  {
    family: 'Hanken Grotesk',
    style: 'normal',
    source: 'hanken-grotesk/HankenGrotesk-Regular.ttf',
  },
  { family: 'Hanken Grotesk', style: 'bold', source: 'hanken-grotesk/HankenGrotesk-Bold.ttf' },
  { family: 'Noto Sans', style: 'normal', source: 'noto-sans/NotoSans-Regular.ttf' },
  { family: 'Noto Sans', style: 'bold', source: 'noto-sans/NotoSans-Bold.ttf' },
];

const HEADER = `/**
 * Generated by scripts/generate-pdf-fonts.ts — do not edit by hand.
 *
 * The base64 payloads are the vendored faces under src/assets/fonts/, licensed
 * under the SIL Open Font License 1.1; the OFL.txt files ship next to them.
 * Import this module dynamically: it is roughly 180 KB and is only needed once
 * a visitor actually asks for the PDF.
 */`;

function familyUnion(faces: readonly EmbeddedFace[]): string {
  const names = [...new Set(faces.map((face) => face.family))];
  if (names.length === 0) throw new Error('No font faces to generate');
  return names.map((name) => `'${name}'`).join(' | ');
}

function faceLiteral(face: EmbeddedFace): string {
  return [
    '  {',
    `    file: '${face.file}',`,
    `    family: '${face.family}',`,
    `    style: '${face.style}',`,
    `    data: '${face.data}',`,
    '  },',
  ].join('\n');
}

export function renderFontModule(faces: readonly EmbeddedFace[]): string {
  return `${HEADER}

export type PdfFontFamily = ${familyUnion(faces)};

export type PdfFontFace = {
  /** Name the face is registered under in jsPDF's virtual file system. */
  file: string;
  family: PdfFontFamily;
  style: 'normal' | 'bold';
  /** Base64-encoded TrueType payload. */
  data: string;
};

export const PDF_FONT_FACES: readonly PdfFontFace[] = [
${faces.map(faceLiteral).join('\n')}
];
`;
}

async function loadFace(face: FaceSource): Promise<EmbeddedFace> {
  const bytes = await readFile(new URL(face.source, FONT_ROOT));
  if (bytes.length === 0) throw new Error(`Empty font face: ${face.source}`);
  return { ...face, file: basename(face.source), data: bytes.toString('base64') };
}

async function main(): Promise<void> {
  const faces = await Promise.all(FACES.map(loadFace));
  const next = renderFontModule(faces);
  const current = await readFile(OUTPUT, 'utf8').catch(() => null);
  if (current === next) {
    process.stdout.write('pdf-fonts.ts is already up to date.\n');
    return;
  }
  await writeFile(OUTPUT, next, 'utf8');
  const kilobytes = faces.map((face) => `${face.file} ${Math.round(face.data.length / 1024)} KB`);
  process.stdout.write(`Wrote ${fileURLToPath(OUTPUT)}\n  ${kilobytes.join('\n  ')}\n`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main().catch((error: unknown) => {
    process.stderr.write(`${error instanceof Error ? error.message : 'unknown'}\n`);
    process.exitCode = 1;
  });
}
